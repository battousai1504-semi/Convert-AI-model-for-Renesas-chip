#!/usr/bin/env python3
"""Join line OCR predictions back into manually labeled whole plates."""
import argparse
import csv
import json
from pathlib import Path

from ocr_batch import normalize, edit_distance


def evaluate(dataset, records):
    predictions = {}
    for row in records:
        name = row['image']
        if name in predictions:
            raise ValueError(f'Duplicate prediction: {name}')
        if row['status'] not in ('ok', 'error'):
            raise ValueError(f'Unexpected prediction status: {name}')
        predictions[name] = row
    expected = [line['image'] for plate in dataset['plates'] for line in plate['lines']]
    if len(expected) != len(set(expected)) or set(predictions) != set(expected):
        raise ValueError('Prediction CSV and dataset image lists do not match exactly')
    if not expected:
        raise ValueError('Dataset is empty')
    devices = {row['device'] for row in records}
    if len(devices) != 1:
        raise ValueError('Use one OCR device CSV at a time')
    rows = []
    for plate in dataset['plates']:
        lines = plate['lines']
        outputs = [predictions[line['image']] for line in lines]
        if len(lines) not in (1, 2):
            raise ValueError('Expected one or two lines per plate')
        for line, output in zip(lines, outputs):
            if normalize(output.get('expected_text', '')) != normalize(line['text']):
                raise ValueError('OCR CSV has different or missing labels; rerun ocr_batch.py with --labels')
        # Require every component to succeed. No partial line can count as an
        # exact whole-plate match, even when concatenated text happens to match.
        prediction = ''.join(normalize(row['prediction']) for row in outputs)
        target = ''.join(normalize(line['text']) for line in lines)
        if not target:
            raise ValueError('Missing ground truth')
        error = any(row['status'] != 'ok' for row in outputs)
        rows.append({'plate_id': plate['plate_id'], 'group_id': plate['group_id'],
                     'line_count': len(lines), 'expected_text': target,
                     'prediction': prediction, 'status': 'error' if error else 'ok',
                     'exact_match': int(not error and prediction == target),
                     'edit_distance': edit_distance(prediction, target)})
    def metrics(items):
        characters = sum(len(row['expected_text']) for row in items)
        return {'plates': len(items), 'errors': sum(row['status'] != 'ok' for row in items),
                'exact_plate_accuracy': sum(row['exact_match'] for row in items) / len(items) if items else None,
                'character_error_rate': sum(row['edit_distance'] for row in items) / characters if characters else None}
    return rows, {'device': next(iter(devices)), 'overall': metrics(rows),
                  'one_line': metrics([r for r in rows if r['line_count'] == 1]),
                  'two_line': metrics([r for r in rows if r['line_count'] == 2]),
                  'source_groups': len({r['group_id'] for r in rows}),
                  'scope': 'Manually selected line crops. Excludes detection, automatic line splitting and video event recognition.',
                  'normalization': 'Uppercase ASCII alphanumerics; no lookalike substitution. Failed lines prevent whole-plate matches.'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', default='data/vn_ocr_v1/dataset.json')
    parser.add_argument('--predictions', required=True, help='ocr_cpu.csv or ocr_cuda.csv from ocr_batch.py')
    parser.add_argument('--output', default='results/vn_plate_evaluation')
    args = parser.parse_args(argv)
    try:
        from annotate_plates import load_dataset
        dataset_path = Path(args.dataset)
        if dataset_path.name != 'dataset.json' or not dataset_path.is_file():
            raise ValueError('Use the dataset.json generated by annotate_plates.py')
        dataset = load_dataset(dataset_path.parent)
        with Path(args.predictions).open(encoding='utf-8-sig', newline='') as handle:
            records = list(csv.DictReader(handle))
        rows, report = evaluate(dataset, records)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.error(str(exc))
    destination = Path(args.output)
    destination.mkdir(parents=True, exist_ok=True)
    with (destination / 'plate_evaluation.csv').open('w', encoding='utf-8-sig', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (destination / 'plate_summary.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print(f'Saved: {destination.resolve()}')


if __name__ == '__main__':
    main()
